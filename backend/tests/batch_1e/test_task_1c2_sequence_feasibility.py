class TestExcludeJobId:
    def test_exclude_removes_job_from_sequence(self, db_session):
        """Excluded job is not in the sequence so no drive-time check is performed."""
        cust = _make_customer(db_session)
        pred_addr = _make_address(db_session)
        prop_addr = _make_address(db_session, lat=39.95, lon=-75.16)
        pred_site = _make_site(db_session, cust.id, address=pred_addr)
        prop_site = _make_site(db_session, cust.id, address=prop_addr)

        pred_job = _make_scheduled_job(
            db_session,
            cust.id,
            pred_site.id,
            start=_NOW,
            end=_NOW + timedelta(hours=2),
        )
        _assign_tech(db_session, pred_job.id)

        # Without exclusion: gap=5 min < drive=30 min → conflict
        with _patch_drive_time(30):
            result_with_conflict = check_sequence_feasibility(
                db_session,
                _TEST_TENANT_ID,
                _TEST_USER_ID,
                proposed_start=_NOW + timedelta(hours=2, minutes=5),
                proposed_end=_NOW + timedelta(hours=4),
                proposed_site_id=prop_site.id,
            )
        assert result_with_conflict["is_feasible"] is False

        # With exclusion: predecessor is excluded → no adjacent jobs → feasible
        with _patch_drive_time(30):
            result_excluded = check_sequence_feasibility(
                db_session,
                _TEST_TENANT_ID,
                _TEST_USER_ID,
                proposed_start=_NOW + timedelta(hours=2, minutes=5),
                proposed_end=_NOW + timedelta(hours=4),
                proposed_site_id=prop_site.id,
                exclude_job_id=pred_job.id,
            )
        assert result_excluded["is_feasible"] is True


