_TEST_USER_ID = uuid.UUID("00000000-0000-0000-0000-000000000002")

_NOW = datetime(2030, 6, 15, 8, 0, 0, tzinfo=UTC)  # fixed anchor — avoids flakiness


def _get_draft_status_id(db: Session) -> uuid.UUID:
    """Resolve the global 'draft' JobStatus id at runtime.

    The UUID is generated by gen_random_uuid() in the Alembic seed migration
    so it is not stable across environments. Always look it up by code.
    """
    status = db.exec(
        select(JobStatus)
        .where(JobStatus.code == "draft")
        .where(JobStatus.tenant_id == None)
    ).first()
    if status is None:
        raise RuntimeError(
            "Global 'draft' JobStatus not found — run seed migrations first."
        )
    return status.id


