"""
Task 1-C-2: Sequence Feasibility Check — Service Unit Tests

Covers ``check_sequence_feasibility()`` in ``scheduling_service.py``.

Scenarios tested:
  * No existing jobs → trivially feasible (is_feasible=True, conflicts=[])
  * No site address on proposed job → soft warning, not a hard conflict
  * Sufficient gap between predecessor and proposed → feasible
  * Insufficient gap between predecessor and proposed → drive_time conflict
  * Insufficient gap between proposed and successor → drive_time conflict
  * Both predecessor and successor conflict → two drive_time conflicts
  * Missing origin address (predecessor has no linked address) → drive_time_warning
  * Missing destination address (successor has no linked address) → drive_time_warning
  * Map provider error → drive_time_warning (soft)
  * exclude_job_id removes that job from the sequence
  * ``is_feasible`` is False only when conflict_type == "drive_time" (warnings don't block)

All DB interactions use the ``db_session`` fixture (postgres + rollback) from conftest.py.
Map calls are always patched — no real HTTP or haversine math in these tests.
"""

