def _make_customer(db: Session) -> Customer:
    cust = Customer(
        id=uuid.uuid4(),
        tenant_id=_TEST_TENANT_ID,
        display_name=f"SeqTest Customer {uuid.uuid4().hex[:6]}",
        type="person",
        is_active=True,
    )
    db.add(cust)
    db.flush()
    return cust


def _make_address(
    db: Session,
    lat: float = 40.7128,
    lon: float = -74.0060,
) -> Address:
    addr = Address(
        id=uuid.uuid4(),
        tenant_id=_TEST_TENANT_ID,
        line1="1 Test St",
        city="Springfield",
        state="IL",
        postal_code="62701",
        country="US",
        latitude=Decimal(str(lat)),
        longitude=Decimal(str(lon)),
        is_active=True,
    )
    db.add(addr)
    db.flush()
    return addr


def _make_site(
    db: Session,
    customer_id: uuid.UUID,
    address: Address | None = None,
) -> Site:
    site = Site(
        id=uuid.uuid4(),
        tenant_id=_TEST_TENANT_ID,
        customer_id=customer_id,
        is_active=True,
    )
    db.add(site)
    db.flush()

    if address is not None:
        ea = EntityAddress(
            id=uuid.uuid4(),
            tenant_id=_TEST_TENANT_ID,
            entity_type_code="site",
            entity_id=site.id,
            address_id=address.id,
            address_type_code="service_location",
            is_primary=True,
            is_active=True,
        )
        db.add(ea)
        db.flush()

    return site


def _make_scheduled_job(
    db: Session,
    customer_id: uuid.UUID,
    site_id: uuid.UUID,
    start: datetime,
    end: datetime,
) -> Job:
    # Resolve 'draft' status id at runtime — UUID is seeded by gen_random_uuid()
    # and is not stable across environments.
    job = Job(
        id=uuid.uuid4(),
        tenant_id=_TEST_TENANT_ID,
        customer_id=customer_id,
        site_id=site_id,
        status_id=_get_draft_status_id(db),
        scheduled_start_at=start,
        scheduled_end_at=end,
        is_active=True,
    )
    db.add(job)
    db.flush()
    return job


def _assign_tech(db: Session, job_id: uuid.UUID) -> JobTechAssignment:
    assignment = JobTechAssignment(
        id=uuid.uuid4(),
        tenant_id=_TEST_TENANT_ID,
        job_id=job_id,
        user_id=_TEST_USER_ID,
        role="primary",
        ordinal=1,
        assigned_at=_NOW,
        assigned_by_user_id=_TEST_USER_ID,
        is_active=True,
    )
    db.add(assignment)
    db.flush()
    return assignment


# ---------------------------------------------------------------------------
# Helper: patch map_service to return a fixed drive time
# ---------------------------------------------------------------------------


def _patch_drive_time(minutes: int):
    """Context manager that patches get_drive_time_minutes to return ``minutes``."""
    return patch(
        "services.scheduling_service.get_drive_time_minutes",
        return_value=minutes,
    )


