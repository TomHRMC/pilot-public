class TestInsufficientGap:
    def test_predecessor_too_close_yields_drive_time_conflict(self, db_session):
        """Predecessor ends 20 min before proposed starts; drive takes 45 min → conflict."""
        cust = _make_customer(db_session)
        pred_addr = _make_address(db_session)
        prop_addr = _make_address(db_session, lat=39.95, lon=-75.16)
        pred_site = _make_site(db_session, cust.id, address=pred_addr)
        prop_site = _make_site(db_session, cust.id, address=prop_addr)

        pred_job = _make_scheduled_job(
            db_session,
            cust.id,
            pred_site.id,
            start=_NOW,
            end=_NOW + timedelta(hours=2),
        )
        _assign_tech(db_session, pred_job.id)

        with _patch_drive_time(45):
            result = check_sequence_feasibility(
                db_session,
                _TEST_TENANT_ID,
                _TEST_USER_ID,
                proposed_start=_NOW + timedelta(hours=2, minutes=20),  # gap = 20 min
                proposed_end=_NOW + timedelta(hours=4, minutes=20),
                proposed_site_id=prop_site.id,
            )

        assert result["is_feasible"] is False
        drive_conflicts = [
            c for c in result["conflicts"] if c["conflict_type"] == "drive_time"
        ]
        assert len(drive_conflicts) == 1
        assert drive_conflicts[0]["gap_minutes"] == 20
        assert drive_conflicts[0]["drive_time_minutes"] == 45
        assert drive_conflicts[0]["conflicting_entity_id"] == str(pred_job.id)

    def test_successor_too_close_yields_drive_time_conflict(self, db_session):
        """Proposed ends 10 min before successor starts; drive takes 30 min → conflict."""
        cust = _make_customer(db_session)
        succ_addr = _make_address(db_session)
        prop_addr = _make_address(db_session, lat=39.95, lon=-75.16)
        succ_site = _make_site(db_session, cust.id, address=succ_addr)
        prop_site = _make_site(db_session, cust.id, address=prop_addr)

        succ_job = _make_scheduled_job(
            db_session,
            cust.id,
            succ_site.id,
            start=_NOW
            + timedelta(hours=3, minutes=10),  # gap = 10 min after proposed ends
            end=_NOW + timedelta(hours=5),
        )
        _assign_tech(db_session, succ_job.id)

        with _patch_drive_time(30):
            result = check_sequence_feasibility(
                db_session,
                _TEST_TENANT_ID,
                _TEST_USER_ID,
                proposed_start=_NOW + timedelta(hours=1),
                proposed_end=_NOW + timedelta(hours=3),  # proposed ends at T+3h
                proposed_site_id=prop_site.id,
            )

        assert result["is_feasible"] is False
        drive_conflicts = [
            c for c in result["conflicts"] if c["conflict_type"] == "drive_time"
        ]
        assert len(drive_conflicts) == 1
        assert drive_conflicts[0]["gap_minutes"] == 10
        assert drive_conflicts[0]["drive_time_minutes"] == 30
        assert drive_conflicts[0]["conflicting_entity_id"] == str(succ_job.id)

    def test_both_predecessor_and_successor_conflict(self, db_session):
        """Both the preceding and following jobs are too close → two drive_time conflicts."""
        cust = _make_customer(db_session)
        pred_addr = _make_address(db_session)
        succ_addr = _make_address(db_session, lat=40.0, lon=-75.0)
        prop_addr = _make_address(db_session, lat=39.95, lon=-75.16)
        pred_site = _make_site(db_session, cust.id, address=pred_addr)
        succ_site = _make_site(db_session, cust.id, address=succ_addr)
        prop_site = _make_site(db_session, cust.id, address=prop_addr)

        pred_job = _make_scheduled_job(
            db_session,
            cust.id,
            pred_site.id,
            start=_NOW,
            end=_NOW + timedelta(hours=2),
        )
        _assign_tech(db_session, pred_job.id)

        succ_job = _make_scheduled_job(
            db_session,
            cust.id,
            succ_site.id,
            start=_NOW + timedelta(hours=4, minutes=10),  # only 10 min after proposed
            end=_NOW + timedelta(hours=6),
        )
        _assign_tech(db_session, succ_job.id)

        with _patch_drive_time(45):  # drive time for every pair = 45 min
            result = check_sequence_feasibility(
                db_session,
                _TEST_TENANT_ID,
                _TEST_USER_ID,
                proposed_start=_NOW
                + timedelta(hours=2, minutes=15),  # gap from pred = 15 min
                proposed_end=_NOW + timedelta(hours=4),
                proposed_site_id=prop_site.id,
            )

        assert result["is_feasible"] is False
        drive_conflicts = [
            c for c in result["conflicts"] if c["conflict_type"] == "drive_time"
        ]
        assert len(drive_conflicts) == 2


