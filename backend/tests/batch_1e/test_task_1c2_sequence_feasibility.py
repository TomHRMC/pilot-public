class TestNoExistingJobs:
    # Use a unique UUID per test-run to avoid stale assignments from prior runs
    # (hardcoded _TEST_USER_ID may have committed assignments in the test DB)
    _FRESH_USER_ID = uuid.uuid4()

    def test_no_jobs_no_site_is_feasible(self, db_session):
        result = check_sequence_feasibility(
            db_session,
            _TEST_TENANT_ID,
            self._FRESH_USER_ID,
            proposed_start=_NOW,
            proposed_end=_NOW + timedelta(hours=2),
        )
        assert result["is_feasible"] is True
        assert result["conflicts"] == []

    def test_no_jobs_with_site_is_feasible(self, db_session):
        cust = _make_customer(db_session)
        addr = _make_address(db_session)
        site = _make_site(db_session, cust.id, address=addr)

        with _patch_drive_time(30):
            result = check_sequence_feasibility(
                db_session,
                _TEST_TENANT_ID,
                self._FRESH_USER_ID,
                proposed_start=_NOW,
                proposed_end=_NOW + timedelta(hours=2),
                proposed_site_id=site.id,
            )

        assert result["is_feasible"] is True
        assert result["conflicts"] == []


