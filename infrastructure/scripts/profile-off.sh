#!/usr/bin/env bash
set -eo pipefail
# ── Profile OFF: Shutdown to Cost Floor — ATOMIC ─────────────────────────────
# Desired state (runs from ANY prior state — A, B, C, or already off):
#   GPU (g4dn.xlarge)       → stopped    (if provisioned)
#   ECS pilot-web           → 0 tasks    (if ECS provisioned)
#   ECS pilot-api           → 0 tasks    (if ECS provisioned)
#   ECS pilot-celery-worker → 0 tasks    (if ECS provisioned)
#   ECS pilot-celery-beat   → 0 tasks    (if ECS provisioned)
#   Bastion                 → stopped    (if provisioned)
#   site-config.json (S3)   → {"mode":"coming_soon","message":"..."}
#
# Cost floor: ~$102/month
#   RDS PostgreSQL    → always on  (~$28/month — auto-restarts after 7 days if stopped)
#   ElastiCache Redis → always on  (~$13/month — no stop feature)
#   NAT Gateway       → always on  (~$32/month — private subnet outbound internet)
#   ALB               → always on  (~$18/month — no stop feature)
#   S3 + CloudFront   → always on  (~$2/month  — static files, near-zero cost)
#   Route 53          → N/A        (DNS moved to Cloudflare 2026-09-07; R53 zone deleted in HIBERNATE-1)
#   Bastion EIP       → reserved   (~$3.50/month while instance is stopped)
#
# NOTE: Marketing site (pilotfortrades.com) remains accessible via S3/CloudFront.
#       site-config.json switches the site to Coming Soon mode — no form submissions
#       are shown (FastAPI is at 0 tasks). Visitors see the brand Coming Soon page
#       with a mailto:sales@pilotfortrades.com CTA.
# ─────────────────────────────────────────────────────────────────────────────
#
# ── PREREQUISITE: AWS CLI must be authenticated as pilot-admin ─────────────────
#   aws sts get-caller-identity
#   # Expected: "Account": "000000000000"
# ─────────────────────────────────────────────────────────────────────────────

# ── Load infrastructure state (generated by generate-infra-state.sh) ─────────
# Run generate-infra-state.sh after any terraform apply to refresh this file.
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
INFRA_STATE_FILE="$SCRIPT_DIR/.infra-state.env"

if [ ! -f "$INFRA_STATE_FILE" ]; then
  echo "ERROR: .infra-state.env not found."
  echo "Run first: cd infrastructure/scripts && ./generate-infra-state.sh"
  exit 1
fi
source "$INFRA_STATE_FILE"

# Static vars (Terraform resource names — stable)
ACCOUNT_ID="000000000000"
REGION="us-east-1"
CLUSTER="${ECS_CLUSTER:-pilot-production}"
MARKETING_BUCKET="pilot-production-marketing"
DOMAIN="pilotfortrades.com"
# ─────────────────────────────────────────────────────────────────────────────

echo "=== Profile OFF: Shutdown to Cost Floor (atomic) ==="
echo "Account: $(aws sts get-caller-identity --query 'Account' --output text --region $REGION)"
[ "$(aws sts get-caller-identity --query 'Account' --output text --region $REGION)" = "$ACCOUNT_ID" ] || \
  { echo "ERROR: Wrong AWS account — aborting"; exit 1; }

echo ""
echo "Desired state:"
echo "  GPU=stopped  pilot-web=0  API=0  Worker=0  Beat=0  Bastion=stopped"
echo "  site-config.json → coming_soon"
echo ""
echo "Infrastructure state (from .infra-state.env):"
echo "  INFRA_GPU=$INFRA_GPU  INFRA_ECS=$INFRA_ECS  INFRA_BASTION=$INFRA_BASTION  INFRA_STORAGE=$INFRA_STORAGE"
echo ""
echo "⚠️  This will stop all provisioned compute services."
echo "    Marketing site remains live at https://$DOMAIN (S3/CloudFront)."
echo "    Visitors will see the Coming Soon page (mailto CTA, no forms)."
echo "    RDS + Redis + NAT + ALB continue billing (~\$102/month cost floor)."
echo ""
read -p "Proceed? (yes/no): " CONFIRM
[ "$CONFIRM" = "yes" ] || { echo "Aborted."; exit 0; }

# ── Step 1: Scale all ECS services to 0 ──────────────────────────────────────
echo ""
if [ "$INFRA_ECS" = "true" ]; then
  echo "[1/5] ECS services → 0 tasks..."
  aws ecs update-service --cluster "$CLUSTER" --service pilot-web \
    --desired-count 0 --region "$REGION" > /dev/null
  echo "  pilot-web → 0 tasks"

  aws ecs update-service --cluster "$CLUSTER" --service pilot-api \
    --desired-count 0 --region "$REGION" > /dev/null
  echo "  pilot-api → 0 tasks"

  aws ecs update-service --cluster "$CLUSTER" --service pilot-celery-worker \
    --desired-count 0 --region "$REGION" > /dev/null
  echo "  pilot-celery-worker → 0 tasks"

  aws ecs update-service --cluster "$CLUSTER" --service pilot-celery-beat \
    --desired-count 0 --region "$REGION" > /dev/null
  echo "  pilot-celery-beat → 0 tasks"
  echo "  ⚠️  Beat is stopped — scheduled tasks (QB sync, email, cleanup) will NOT run"
else
  echo "[1/5] ECS services → [SKIP] not yet provisioned (Phase 6 Step 6.4)"
fi

# ── Step 2: (No App Runner — sunset April 30 2026) ───────────────────────────
# pilot-web is now the 4th ECS Fargate service — scaled to 0 above in Step 1.
echo ""
echo "[2/5] App Runner → N/A (sunset April 30, 2026 — pilot-web is ECS Fargate)"

# ── Step 3: Stop GPU instance ─────────────────────────────────────────────────
echo ""
if [ "$INFRA_GPU" = "true" ] && [ -n "$GPU_INSTANCE_ID" ]; then
  echo "[3/5] GPU → stopped (saves ~\$390/month when running)..."
  GPU_STATE=$(aws ec2 describe-instances --instance-ids "$GPU_INSTANCE_ID" \
    --query 'Reservations[0].Instances[0].State.Name' --output text --region "$REGION")
  if [ "$GPU_STATE" = "running" ] || [ "$GPU_STATE" = "pending" ]; then
    aws ec2 stop-instances --instance-ids "$GPU_INSTANCE_ID" --region "$REGION" > /dev/null
    echo "  GPU stopping (~2 min)"
  else
    echo "  GPU already $GPU_STATE — no change"
  fi
else
  echo "[3/5] GPU → [SKIP] not yet provisioned (Phase 4 — pending AWS vCPU quota)"
fi

# ── Step 4: Stop Bastion ──────────────────────────────────────────────────────
echo ""
if [ "$INFRA_BASTION" = "true" ] && [ -n "$BASTION_INSTANCE_ID" ]; then
  echo "[4/5] Bastion → stopped (EIP still billed ~\$3.50/month while stopped)..."
  BASTION_STATE=$(aws ec2 describe-instances --instance-ids "$BASTION_INSTANCE_ID" \
    --query 'Reservations[0].Instances[0].State.Name' --output text --region "$REGION")
  if [ "$BASTION_STATE" = "running" ] || [ "$BASTION_STATE" = "pending" ]; then
    aws ec2 stop-instances --instance-ids "$BASTION_INSTANCE_ID" --region "$REGION" > /dev/null
    echo "  Bastion stopping (~1 min)"
  else
    echo "  Bastion already $BASTION_STATE — no change"
  fi
else
  echo "[4/5] Bastion → [SKIP] not yet provisioned"
fi

# ── Step 5: Switch marketing site to Coming Soon mode ────────────────────────
echo ""
echo "[5/5] site-config.json → coming_soon..."
aws s3 cp - "s3://$MARKETING_BUCKET/site-config.json" \
  --cache-control "no-cache, no-store, must-revalidate" \
  --content-type "application/json" <<< \
  '{"mode":"coming_soon","message":"We are putting the finishing touches on Pilot. Sign up to be first in line when we launch."}'
echo "  S3 upload complete"

if [ "$INFRA_STORAGE" = "true" ] && [ -n "$CLOUDFRONT_DIST_ID" ]; then
  aws cloudfront create-invalidation \
    --distribution-id "$CLOUDFRONT_DIST_ID" \
    --paths "/site-config.json" --region us-east-1 > /dev/null
  echo "  CloudFront invalidation issued"
else
  echo "  CloudFront → [SKIP] not yet provisioned"
fi

# ── Status summary ────────────────────────────────────────────────────────────
echo ""
echo "=== Shutdown Status ==="

if [ "$INFRA_ECS" = "true" ]; then
  echo ""
  echo "ECS services (target: all 0 tasks):"
  aws ecs describe-services --cluster "$CLUSTER" \
    --services pilot-web pilot-api pilot-celery-worker pilot-celery-beat \
    --query 'services[*].{Name:serviceName,Running:runningCount,Desired:desiredCount}' \
    --output table --region "$REGION"
else
  echo ""
  echo "ECS services: [not provisioned — Phase 6 required]"
fi

if [ "$INFRA_GPU" = "true" ] && [ -n "$GPU_INSTANCE_ID" ]; then
  echo ""
  echo "GPU state:"
  aws ec2 describe-instances --instance-ids "$GPU_INSTANCE_ID" \
    --query 'Reservations[0].Instances[0].State.Name' --output text --region "$REGION"
else
  echo ""
  echo "GPU state: [not provisioned]"
fi

if [ "$INFRA_BASTION" = "true" ] && [ -n "$BASTION_INSTANCE_ID" ]; then
  echo ""
  echo "Bastion state:"
  aws ec2 describe-instances --instance-ids "$BASTION_INSTANCE_ID" \
    --query 'Reservations[0].Instances[0].State.Name' --output text --region "$REGION"
else
  echo ""
  echo "Bastion state: [not provisioned]"
fi

echo ""
echo "=== Cost Floor Active ==="
echo "Estimated remaining cost: ~\$102/month"
echo ""
echo "What's still running:"
echo "  ✅ Marketing site:  https://$DOMAIN (Coming Soon page — S3/CloudFront)"
echo "  ⛔ Marketing forms: OFFLINE (FastAPI at 0 tasks)"
if [ "$INFRA_ECS" = "true" ]; then
  echo "  ⛔ Web dashboard:   OFFLINE (pilot-web ECS at 0 tasks)"
else
  echo "  ⏳ Web dashboard:   [Phase 6 Step 6.4 required]"
fi
echo "  ⛔ Mobile backend:  OFFLINE (FastAPI at 0 tasks)"
if [ "$INFRA_GPU" = "true" ]; then
  echo "  ⛔ Voice AI:        OFFLINE (GPU stopped)"
else
  echo "  ⏳ Voice AI:        [Phase 4 required — GPU not provisioned]"
fi
echo ""
echo "To restart:"
echo "  ./profile-a-marketing.sh         # Marketing forms only (~\$148/month)"
echo "  ./profile-b-app.sh light         # Web/mobile app       (~\$170/month)"
echo "  ./profile-b-app.sh ai            # Full AI testing      (~\$562/month)"
echo "  ./profile-c-full.sh              # Beta customer ready  (~\$562/month)"

# ── Write profile state ───────────────────────────────────────────────────────
PROFILES_STATE_FILE="$SCRIPT_DIR/.env.profiles"
PROFILE_VALUE="off"
cat > "$PROFILES_STATE_FILE" << EOF
# Written by $(basename "$0") on $(date -u '+%Y-%m-%dT%H:%M:%SZ')
# Read by profile-status.sh to show Expected vs Actual state.
# Gitignored — do not commit.
PROFILE_SET="${PROFILE_VALUE}"
PROFILE_SET_AT="$(date -u '+%Y-%m-%dT%H:%M:%SZ')"
EOF
echo "  Profile state written: PROFILE_SET=${PROFILE_VALUE}"
echo ""
echo "Run ./profile-status.sh to verify current state."
