#!/usr/bin/env bash
set -eo pipefail
# ── Profile C: Full Production-Spec State (demo prep) — ATOMIC ─────────────────────────────
# Desired state (runs from ANY prior state — off, A, B, or C itself):
#   GPU (g4dn.xlarge)       → running   (if provisioned; Voice AI required for beta)
#   Bastion                 → running   (if provisioned — needed for RDS SSH tunnel)
#   ECS pilot-web           → 1 task    (if ECS provisioned; web dashboard required for beta)
#   ECS pilot-api           → 2 tasks   (if ECS provisioned)
#   ECS pilot-celery-worker → 2 tasks   (if ECS provisioned)
#   ECS pilot-celery-beat   → 1 task    (if ECS provisioned)
#   site-config.json (S3)   → {"mode":"live"}
#
# Cost: ~$562/month (same as Profile B ai)
# Use when: preparing a demo. Enforces the full production-equivalent state;
# afterwards run ./profile-status.sh. All rows must be green before any demo.
# ─────────────────────────────────────────────────────────────────────────────
#
# ── PREREQUISITE: AWS CLI must be authenticated as pilot-admin ─────────────────
#   aws sts get-caller-identity
#   # Expected: "Account": "000000000000"
# ─────────────────────────────────────────────────────────────────────────────

# ── Load infrastructure state (generated by generate-infra-state.sh) ─────────
# Run generate-infra-state.sh after any terraform apply to refresh this file.
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
INFRA_STATE_FILE="$SCRIPT_DIR/.infra-state.env"

if [ ! -f "$INFRA_STATE_FILE" ]; then
  echo "ERROR: .infra-state.env not found."
  echo "Run first: cd infrastructure/scripts && ./generate-infra-state.sh"
  exit 1
fi
source "$INFRA_STATE_FILE"

# Static vars (Terraform resource names — stable)
ACCOUNT_ID="000000000000"
REGION="us-east-1"
CLUSTER="${ECS_CLUSTER:-pilot-production}"
MARKETING_BUCKET="pilot-production-marketing"
DOMAIN="pilotfortrades.com"
# ─────────────────────────────────────────────────────────────────────────────

echo "=== Profile C: Full Production-Spec [demo prep] (atomic) ==="
echo "Account: $(aws sts get-caller-identity --query 'Account' --output text --region $REGION)"
[ "$(aws sts get-caller-identity --query 'Account' --output text --region $REGION)" = "$ACCOUNT_ID" ] || \
  { echo "ERROR: Wrong AWS account — aborting"; exit 1; }

echo ""
echo "Desired state:"
echo "  GPU=running  Bastion=running  pilot-web=1  API=2  Worker=2  Beat=1"
echo "  site-config.json → live"
echo ""
echo "Infrastructure state (from .infra-state.env):"
echo "  INFRA_GPU=$INFRA_GPU  INFRA_ECS=$INFRA_ECS  INFRA_STORAGE=$INFRA_STORAGE"
echo ""
read -p "Proceed? (yes/no): " CONFIRM
[ "$CONFIRM" = "yes" ] || { echo "Aborted."; exit 0; }

# ══════════════════════════════════════════════════════════════════════════════
# PHASE 1: Enforce desired service state (atomic — idempotent from any prior state)
# ══════════════════════════════════════════════════════════════════════════════

echo ""
echo "── Phase 1: Enforcing desired state ─────────────────────────────────────"

# Step 1: GPU → running
echo ""
if [ "$INFRA_GPU" = "true" ] && [ -n "$GPU_INSTANCE_ID" ]; then
  echo "[1/6] GPU → running..."
  GPU_STATE=$(aws ec2 describe-instances --instance-ids "$GPU_INSTANCE_ID" \
    --query 'Reservations[0].Instances[0].State.Name' --output text --region "$REGION")
  if [ "$GPU_STATE" = "stopped" ] || [ "$GPU_STATE" = "stopping" ]; then
    aws ec2 start-instances --instance-ids "$GPU_INSTANCE_ID" --region "$REGION" > /dev/null
    echo "  GPU starting (~3-5 min boot + 5-15 min Ollama llama3.1:8b load)"
  elif [ "$GPU_STATE" = "running" ]; then
    echo "  GPU already running — no change"
  else
    echo "  GPU state: $GPU_STATE — waiting for stable state before proceeding"
  fi
else
  echo "[1/6] GPU → [SKIP] not yet provisioned (Phase 4 — pending AWS vCPU quota)"
fi

# Step 2: Bastion → running
echo ""
if [ "$INFRA_BASTION" = "true" ] && [ -n "$BASTION_INSTANCE_ID" ]; then
  echo "[2/6] Bastion → running (needed for RDS SSH tunnel access)..."
  BASTION_STATE=$(aws ec2 describe-instances --instance-ids "$BASTION_INSTANCE_ID" \
    --query 'Reservations[0].Instances[0].State.Name' --output text --region "$REGION")
  if [ "$BASTION_STATE" = "stopped" ] || [ "$BASTION_STATE" = "stopping" ]; then
    aws ec2 start-instances --instance-ids "$BASTION_INSTANCE_ID" --region "$REGION" > /dev/null
    echo "  Bastion starting (~1 min) — EIP: 203.0.113.12 (static)"
  else
    echo "  Bastion already $BASTION_STATE — no change"
  fi
else
  echo "[2/6] Bastion → [SKIP] not yet provisioned"
fi

# Step 3: ECS pilot-web → 1 task (web dashboard required for beta)
echo ""
if [ "$INFRA_ECS" = "true" ]; then
  echo "[3/6] ECS pilot-web → 1 task (web dashboard on)..."
  aws ecs update-service --cluster "$CLUSTER" --service pilot-web \
    --desired-count 1 --region "$REGION" > /dev/null
  echo "  pilot-web → 1 task ✅"
else
  echo "[3/6] ECS pilot-web → [SKIP] not yet provisioned (Phase 6 Step 6.4)"
fi

# Step 4: ECS → 2 API, 2 Worker, 1 Beat
echo ""
if [ "$INFRA_ECS" = "true" ]; then
  echo "[4/6] ECS → API=2, Worker=2, Beat=1..."
  aws ecs update-service --cluster "$CLUSTER" --service pilot-api \
    --desired-count 2 --region "$REGION" > /dev/null
  echo "  pilot-api → 2 tasks"

  aws ecs update-service --cluster "$CLUSTER" --service pilot-celery-worker \
    --desired-count 2 --region "$REGION" > /dev/null
  echo "  pilot-celery-worker → 2 tasks"

  aws ecs update-service --cluster "$CLUSTER" --service pilot-celery-beat \
    --desired-count 1 --region "$REGION" > /dev/null
  echo "  pilot-celery-beat → 1 task"
else
  echo "[4/6] ECS services → [SKIP] not yet provisioned (Phase 6)"
  echo "  After Phase 6 deploys ECS, run: ./generate-infra-state.sh"
fi

# Step 5: site-config.json — live only when ECS running
echo ""
if [ "$INFRA_ECS" = "true" ]; then
  echo "[5/6] site-config.json → live (ECS running)..."
  aws s3 cp - "s3://$MARKETING_BUCKET/site-config.json" \
    --cache-control "no-cache, no-store, must-revalidate" \
    --content-type "application/json" <<< '{"mode":"live"}'
else
  echo "[5/6] site-config.json → coming_soon (ECS not yet deployed)..."
  aws s3 cp - "s3://$MARKETING_BUCKET/site-config.json" \
    --cache-control "no-cache, no-store, must-revalidate" \
    --content-type "application/json" <<< '{"mode":"coming_soon","message":"We are putting the finishing touches on Pilot. Sign up to be first in line when we launch."}'
  echo "  Note: switch to live after Phase 6 ECS deployment + generate-infra-state.sh"
fi
echo "  S3 upload complete"

if [ "$INFRA_STORAGE" = "true" ] && [ -n "$CLOUDFRONT_DIST_ID" ]; then
  aws cloudfront create-invalidation \
    --distribution-id "$CLOUDFRONT_DIST_ID" \
    --paths "/site-config.json" --region us-east-1 > /dev/null
  echo "  CloudFront invalidation issued"
else
  echo "  CloudFront → [SKIP] not yet provisioned"
fi

# Step 6: Status summary
echo ""
echo "[6/6] Status:"

if [ "$INFRA_GPU" = "true" ] && [ -n "$GPU_INSTANCE_ID" ]; then
  echo ""
  echo "GPU state:"
  aws ec2 describe-instances --instance-ids "$GPU_INSTANCE_ID" \
    --query 'Reservations[0].Instances[0].State.Name' --output text --region "$REGION"
else
  echo ""
  echo "GPU state: [not provisioned]"
fi

if [ "$INFRA_ECS" = "true" ]; then
  echo ""
  echo "ECS services:"
  aws ecs describe-services --cluster "$CLUSTER" \
    --services pilot-web pilot-api pilot-celery-worker pilot-celery-beat \
    --query 'services[*].{Name:serviceName,Running:runningCount,Desired:desiredCount}' \
    --output table --region "$REGION"
else
  echo ""
  echo "ECS services: [not provisioned — Phase 6 required]"
fi

echo ""
echo "=== Profile C [full] Active ==="
echo "Cost: ~\$562/month (GPU + all ECS running)"
echo ""
echo "Next step: run profile-status.sh to verify all resources have reached target state."
echo "  ./profile-status.sh"
echo ""
echo "Re-run as many times as needed until all rows show ✅."
echo "GPU boot: ~3-5 min | Ollama model load: ~5-15 min | ECS tasks: ~2-3 min"

# ── Write profile state ───────────────────────────────────────────────────────
PROFILES_STATE_FILE="$SCRIPT_DIR/.env.profiles"
PROFILE_VALUE="full"
cat > "$PROFILES_STATE_FILE" << EOF
# Written by $(basename "$0") on $(date -u '+%Y-%m-%dT%H:%M:%SZ')
# Read by profile-status.sh to show Expected vs Actual state.
# Gitignored — do not commit.
PROFILE_SET="${PROFILE_VALUE}"
PROFILE_SET_AT="$(date -u '+%Y-%m-%dT%H:%M:%SZ')"
EOF
echo "  Profile state written: PROFILE_SET=${PROFILE_VALUE}"
echo ""
echo "Run ./profile-status.sh to verify current state."
