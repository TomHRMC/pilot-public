#!/usr/bin/env bash
set -eo pipefail
# ── generate-infra-state.sh ───────────────────────────────────────────────────
# Queries live Terraform state and writes .infra-state.env for use by profile scripts.
# Run this once after any terraform apply, and whenever Terraform creates new resources.
#
# Usage:
#   cd infrastructure/scripts
#   ./generate-infra-state.sh
#
# Output: infrastructure/scripts/.infra-state.env (gitignored)
# ─────────────────────────────────────────────────────────────────────────────

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
TF_DIR="$(cd "$SCRIPT_DIR/../../infrastructure/terraform/environments/production" 2>/dev/null || cd "$SCRIPT_DIR/../terraform/environments/production")" && TF_DIR="$(pwd)"
# Resolve TF_DIR relative to SCRIPT_DIR
TF_DIR="$SCRIPT_DIR/../terraform/environments/production"
OUTPUT_FILE="$SCRIPT_DIR/.infra-state.env"
REGION="us-east-1"
ACCOUNT_ID="000000000000"

echo "=== generate-infra-state.sh ==="
echo "Script dir:    $SCRIPT_DIR"
echo "Terraform dir: $TF_DIR"
echo "Output file:   $OUTPUT_FILE"
echo ""

# Verify correct AWS account
CURRENT_ACCOUNT=$(aws sts get-caller-identity --query 'Account' --output text --region "$REGION" 2>/dev/null || echo "")
if [ "$CURRENT_ACCOUNT" != "$ACCOUNT_ID" ]; then
  echo "ERROR: Wrong AWS account ($CURRENT_ACCOUNT) — must be $ACCOUNT_ID"
  echo "Run: aws sts get-caller-identity  # to check current identity"
  exit 1
fi
echo "AWS account: $CURRENT_ACCOUNT ✅"

# ── Helper: get terraform output, return empty string if not found ────────────
tf_output() {
  local key="$1"
  (cd "$TF_DIR" && terraform output -raw "$key" 2>/dev/null) || echo ""
}

# ── Resolve resource IDs from Terraform outputs ───────────────────────────────
echo ""
echo "Resolving resource IDs from terraform output..."

# GPU instance ID — query EC2 by name tag (not a terraform output)
GPU_INSTANCE_ID=$(aws ec2 describe-instances \
  --filters "Name=tag:Name,Values=pilot-production-gpu" "Name=instance-state-name,Values=running,stopped,stopping,pending" \
  --query 'Reservations[0].Instances[0].InstanceId' \
  --output text --region "$REGION" 2>/dev/null || echo "")
# "None" from AWS CLI means no match
[ "$GPU_INSTANCE_ID" = "None" ] && GPU_INSTANCE_ID=""

# Bastion instance ID — query EC2 by name tag
BASTION_INSTANCE_ID=$(aws ec2 describe-instances \
  --filters "Name=tag:Name,Values=pilot-production-bastion" "Name=instance-state-name,Values=running,stopped,stopping,pending" \
  --query 'Reservations[0].Instances[0].InstanceId' \
  --output text --region "$REGION" 2>/dev/null || echo "")
[ "$BASTION_INSTANCE_ID" = "None" ] && BASTION_INSTANCE_ID=""

# CloudFront distribution ID — from Terraform output
CLOUDFRONT_DIST_ID=$(tf_output "cloudfront_distribution_id")

# ECS cluster name — from Terraform output
ECS_CLUSTER=$(tf_output "ecs_cluster_name")

# ── Determine feature flags ───────────────────────────────────────────────────

# Networking: bastion public IP exists = Phase 1 complete
BASTION_IP=$(tf_output "bastion_public_ip")
if [ -n "$BASTION_IP" ] && [ "$BASTION_IP" != "null" ]; then
  INFRA_NETWORKING="true"
else
  INFRA_NETWORKING="false"
fi

# Database: query RDS directly (rds_endpoint is sensitive, can't use tf output)
RDS_COUNT=$(aws rds describe-db-instances \
  --filters "Name=db-instance-id,Values=pilot-production" \
  --query 'length(DBInstances)' \
  --output text --region "$REGION" 2>/dev/null || echo "0")
[ "$RDS_COUNT" != "0" ] && INFRA_DATABASE="true" || INFRA_DATABASE="false"

# Storage: CloudFront distribution ID exists = Phase 5 compute complete
if [ -n "$CLOUDFRONT_DIST_ID" ] && [ "$CLOUDFRONT_DIST_ID" != "null" ]; then
  INFRA_STORAGE="true"
else
  INFRA_STORAGE="false"
fi

# Bastion: instance ID found in EC2
[ -n "$BASTION_INSTANCE_ID" ] && INFRA_BASTION="true" || INFRA_BASTION="false"

# GPU: instance ID found in EC2
[ -n "$GPU_INSTANCE_ID" ] && INFRA_GPU="true" || INFRA_GPU="false"

# ECS: verify all 4 services are ACTIVE in AWS (pilot-api, worker, beat, web)
INFRA_ECS="false"
ECS_CLUSTER_NAME="${ECS_CLUSTER:-pilot-production}"
if [ -n "$ECS_CLUSTER_NAME" ]; then
  ACTIVE_COUNT=$(aws ecs describe-services \
    --cluster "$ECS_CLUSTER_NAME" \
    --services pilot-api pilot-celery-worker pilot-celery-beat pilot-web \
    --query 'services[?status==`ACTIVE`] | length(@)' \
    --output text --region "$REGION" 2>/dev/null || echo "0")
  [ "$ACTIVE_COUNT" = "4" ] && INFRA_ECS="true"
fi

# ── Write .infra-state.env ─────────────────────────────────────────────────────
TIMESTAMP=$(date -u +"%Y-%m-%dT%H:%M:%SZ")

cat > "$OUTPUT_FILE" << EOF
# Auto-generated by generate-infra-state.sh — DO NOT EDIT
# Last generated: $TIMESTAMP
# Terraform dir:  $TF_DIR
# AWS account:    $ACCOUNT_ID
#
# Usage: source "\$(dirname "\${BASH_SOURCE[0]}")/.infra-state.env"
# All profile scripts source this file at startup.

# ── Provisioned resource IDs ──────────────────────────────────────────────────
GPU_INSTANCE_ID="$GPU_INSTANCE_ID"
BASTION_INSTANCE_ID="$BASTION_INSTANCE_ID"
CLOUDFRONT_DIST_ID="$CLOUDFRONT_DIST_ID"
ECS_CLUSTER="${ECS_CLUSTER_NAME}"

# ── Feature flags: "true" = resource exists in Terraform/AWS state ───────────
INFRA_NETWORKING="$INFRA_NETWORKING"
INFRA_DATABASE="$INFRA_DATABASE"
INFRA_STORAGE="$INFRA_STORAGE"
INFRA_BASTION="$INFRA_BASTION"
INFRA_GPU="$INFRA_GPU"
INFRA_ECS="$INFRA_ECS"
EOF

echo ""
echo "=== Infrastructure State ==="
echo "  INFRA_NETWORKING:  $INFRA_NETWORKING"
echo "  INFRA_DATABASE:    $INFRA_DATABASE"
echo "  INFRA_STORAGE:     $INFRA_STORAGE"
echo "  INFRA_BASTION:     $INFRA_BASTION   (ID: ${BASTION_INSTANCE_ID:-<not provisioned>})"
echo "  INFRA_GPU:         $INFRA_GPU       (ID: ${GPU_INSTANCE_ID:-<not provisioned>})"
echo "  INFRA_ECS:         $INFRA_ECS       (ECS services: pilot-api/worker/beat/web — all 4 must be ACTIVE)"
echo ""
echo "Written to: $OUTPUT_FILE"
echo ""
echo "Run this script again after any terraform apply that adds new resources."
